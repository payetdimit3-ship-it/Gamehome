#!/usr/bin/env python3
"""Hutengeneza pages 54 za ziada (user + admin) kutoka kwenye pages halisi.
Endesha kutoka kwenye root ya mradi:  python3 tools/build-pages.py
Kila ukurasa unaotengenezwa ni ukurasa KAMILI (si redirect) wenye anwani yake mwenyewe.
Ukibadilisha ukurasa halisi (mf. shop.html au admin.html), endesha script hii tena ili nakala zisasishwe."""
import re, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
rd = lambda f: open(f, encoding='utf-8').read()

# ---- user pages: file -> (ukurasa halisi, cat ya kulazimisha | None, kichwa)
USER = {
 'home':('index',None,'Home'), 'store':('shop',None,'Store'), 'games':('categories',None,'Games'),
 'psp-gaming':('shop','psp','PSP Gaming'), 'ps2-gaming':('shop','ps2','PS2 Gaming'), 'ps3-gaming':('shop','ps3','PS3 Gaming'),
 'nintendo-switch':('shop','switch','Nintendo Switch'), 'android-gaming':('shop','android','Android Gaming'), 'pc-gaming':('shop','pc','PC Gaming'),
 'product-details':('product',None,'Product Details'),
 'my-orders':('myorders',None,'My Orders'), 'requests-transactions':('myorders',None,'Requests / Transactions'),
 'contact-support':('contact',None,'Contact / Support'), 'faq-help':('faq',None,'FAQ / Help'),
 'community-chat':('chat',None,'Community Chat'), 'health-assistant':('health',None,'Health Assistant'), 'ai-assistant':('ai',None,'AI Assistant'),
 'my-games-library':('mygames',None,'My Games Library'), 'gift-cards':('giftcards',None,'Gift Cards'),
 'efootball-topup':('efootball',None,'eFootball Top Up'), 'cloud-gaming':('cloudgaming',None,'Cloud Gaming'),
 'tournament':('tournaments',None,'Tournament'),
 'live-tv-esports':('live',None,'Live TV / eSports'), 'live-football-watch':('live',None,'Live Football / Watch Match'),
 'live-scores':('livescores',None,'Live Scores'), 'betting':('livescores',None,'Betting — Live Matches'),
 'live-movies-player':('movies',None,'Live Movies Player'), 'game-trailer':('movies',None,'Game Trailer'),
}
# ---- admin pages: file -> (tab ya admin.html, kichwa)
ADMIN = {
 'dashboard':('overview','Admin Dashboard'), 'analytics':('overview','Analytics'), 'reports':('overview','Reports'),
 'games-management':('products','Games Management'), 'products-management':('products','Products Management'),
 'efootball-topup-management':('products','eFootball / Top Up Management'), 'gift-cards-management':('products','Gift Cards Management'),
 'cloud-gaming-management':('products','Cloud Gaming Management'),
 'orders-sales':('orders','Orders & Sales'), 'withdraw-requests':('withdrawals','Withdraw Requests'),
 'users-management':('customers','Users Management'), 'students-management':('customers','Students Management'),
 'hero-homepage-management':('hero','Hero / Homepage Management'), 'coupons-discounts':('coupons','Coupons & Discounts'),
 'marketplace-management':('marketplace','Marketplace Management'), 'support-tickets':('requests','Support Tickets'),
 'storage-server':('security','Storage & Server'), 'web-content':('webcontent','Website Content'),
 'movies-management':('media','Movies Management'), 'trailers-management':('media','Trailers Management'),
 'live-matches-management':('media','Live Matches Management'), 'sports-tv-management':('tvchannels','Sports TV Management'),
 'sports-news-management':('news','Sports News Management'), 'news-management':('news','Habari za Michezo'), 'content-management':('contentposts','Content Posts'), 'tv-management':('tvchannels','TV Channels'), 'admin-chat':('aichat','AI Chat'), 'courses-management':('media','Courses Management'),
 'lessons-videos-management':('media','Lessons / Videos Management'),
}
GEN = '<!-- GENERATED by tools/build-pages.py from %s.html — usihariri hapa, hariri chanzo kisha endesha script -->\n'
title = lambda h, t: re.sub(r'<title>.*?</title>', '<title>%s — LIFEISGAMETZ</title>' % t.replace('&','&amp;'), h, count=1, flags=re.S)
def put(head_inject, h):
    return h.replace('<head>', '<head>\n' + head_inject, 1) if '<head>' in h else head_inject + h

made = 0
for page, (src, cat, t) in USER.items():
    h = rd(src + '.html')
    assert 'GENERATED by' not in h, src
    h = title(h, t)
    if cat:   # shop.html inasoma ?cat= — tunaiweka bila kubadilisha URL ya faili
        h = put('<script>if(!new URLSearchParams(location.search).get("cat"))history.replaceState(null,"",location.pathname+"?cat=%s"+location.hash);</script>' % cat, h)
    open(page + '.html', 'w', encoding='utf-8').write(GEN % src + h); made += 1

admin_src = rd('admin.html'); assert 'GENERATED by' not in admin_src
for page, (tab, t) in ADMIN.items():
    h = title(admin_src, t)
    inj = ('<script>if(!location.hash)history.replaceState(null,"",location.pathname+location.search+"#tab-%s");</script>\n'
           '<style>.admin-tabs{display:none!important}.adm-focus{display:flex;align-items:center;gap:12px;flex-wrap:wrap;margin:6px 0 16px}'
           '.adm-focus h1{margin:0;font-size:26px}.adm-focus a{color:#a78bfa;font-size:13px;font-weight:700;text-decoration:none}</style>') % tab
    h = put(inj, h)
    # kichwa cha ukurasa juu ya tabs
    h = h.replace('<div class="admin-tabs">', '<div class="adm-focus"><h1>%s</h1><a href="admin.html">← Admin Panel yote</a></div>\n    <div class="admin-tabs">' % t.replace('&','&amp;'), 1)
    open(page + '.html', 'w', encoding='utf-8').write(GEN % 'admin' + h); made += 1

# ---- sidebar highlight: nakala zichukuliwe kama ukurasa wake halisi
sh = rd('zoneplay-shell.js')
alias = {p + '.html': s + '.html' for p, (s, c, t) in USER.items()}
body = ','.join("'%s':'%s'" % kv for kv in sorted(alias.items()))
block = "/*GEN-ALIAS*/Object.assign(ALIAS,{%s});/*END-GEN-ALIAS*/" % body
if '/*GEN-ALIAS*/' in sh:
    sh = re.sub(r'/\*GEN-ALIAS\*/.*?/\*END-GEN-ALIAS\*/', lambda m: block, sh, flags=re.S)
else:
    anchor = "    'courses.html':'academy.html','refund.html':'terms.html'};"
    assert anchor in sh
    sh = sh.replace(anchor, anchor + "\n  " + block, 1)
open('zoneplay-shell.js', 'w', encoding='utf-8').write(sh)
print('pages zilizotengenezwa:', made)
